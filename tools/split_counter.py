def draw(character, strokes, radius):
    # The slightly thinner crossbars leave the two counters of an 8 open in bold.
    stretch = 1.28
    shapes = []
    for stroke in strokes:
        if len(stroke) == 1:
            x, y = stroke[0]
            shapes.append(box(x - radius, y * stretch - radius,
                              x + radius, y * stretch + radius))
        else:
            line = LineString([(x, y * stretch) for x, y in stroke])
            shapes.append(line.buffer(radius, cap_style="flat", join_style="mitre",
                                      mitre_limit=1.7))
    return scale(unary_union(shapes), xfact=1, yfact=1 / stretch, origin=(0, 0))
