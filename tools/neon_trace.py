def bent_path(points):
    """Ease each bend along a short quadratic arc, preserving open terminals."""
    closed = points[0] == points[-1]
    knots = points[:-1] if closed else points
    result = [] if closed else [knots[0]]
    indices = range(len(knots)) if closed else range(1, len(knots) - 1)
    for i in indices:
        x, y = knots[i]
        px, py = knots[i - 1]
        nx, ny = knots[(i + 1) % len(knots)]
        before, after = hypot(px - x, py - y), hypot(nx - x, ny - y)
        if not before or not after:
            continue
        trim = min(0.6, before * 0.4, after * 0.4)
        ax, ay = x + (px - x) * trim / before, y + (py - y) * trim / before
        bx, by = x + (nx - x) * trim / after, y + (ny - y) * trim / after
        for t in (0, 0.25, 0.5, 0.75, 1):
            u = 1 - t
            result.append((u*u*ax + 2*t*u*x + t*t*bx, u*u*ay + 2*t*u*y + t*t*by))
    result.append(result[0] if closed else knots[-1])
    return result


def draw(character, strokes, radius):
    tubes = []
    for points in strokes:
        if len(points) == 1:
            tube = Point(points[0])
        else:
            tube = LineString(bent_path(points))
        tubes.append(tube.buffer(radius, quad_segs=5, cap_style="round", join_style="round"))
    return unary_union(tubes).simplify(0.012, preserve_topology=True)
