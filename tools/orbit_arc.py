def arc(cx, cy, rx, ry, start=0, end=360):
    """Sample the centerline of an ellipse on the shared seven-unit cap grid."""
    steps = ceil(abs(end - start) / 12)
    points = []
    for i in range(steps + 1):
        angle = radians(start + (end - start) * i / steps)
        points.append(f"{cx + rx * cos(angle):.3f},{cy + ry * sin(angle):.3f}")
    return " ".join(points)


