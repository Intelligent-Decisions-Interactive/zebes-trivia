def draw(character, strokes, radius):
    contours = []
    for points in strokes:
        centerline = Point(points[0]) if len(points) == 1 else LineString(points)
        contours.append(centerline.buffer(radius, quad_segs=7, cap_style="round", join_style="round"))
    return unary_union(contours).simplify(0.009, preserve_topology=True)
